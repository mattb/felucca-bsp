"""Generate the capture 160/147 resampler's symmetric floating-point polyphase FIR.

A 32-input-frame Blackman-windowed sinc, cutoff 0.45 cycles/input frame.
Retain the original Q30 unity-normalized design, then emit float coefficients.
Only the first 80 phases are stored; usb.c reverses phase 159-p to obtain the other half.
Uses only Python's standard library. Run from any directory; stdout is C.
"""
import math

L, M, N, Q = 160, 147, 32, 30
print('/* SPDX-License-Identifier: MPL-2.0\n * Generated by tools/gen_uac_fir.py; do not edit. */')
print(f'#define UAC_FIR_L {L}u\n#define UAC_FIR_M {M}u\n#define UAC_FIR_N {N}u')
print(f'static const float UAC_FIR[{L // 2}][{N}] = {{')
for phase in range(L // 2):
    center = (N - 1) / 2 + (phase - (L - 1) / 2) / L
    taps = []
    for k in range(N):
        x = k - center
        sinc = math.sin(2 * math.pi * .45 * x) / (math.pi * x) if x else .9
        window = .42 + .5 * math.cos(math.pi * x / (N / 2)) + .08 * math.cos(2 * math.pi * x / (N / 2))
        taps.append(sinc * window)
    total = sum(taps)
    coeff = [round(t / total * (1 << Q)) for t in taps]
    coeff[round(center)] += (1 << Q) - sum(coeff)
    print('    {' + ', '.join(f'{c / (1 << Q):.9e}f' for c in coeff) + '},')
print('};')
